import { useState } from "react";
import { useNavigate } from "react-router-dom";
import { apiError } from "../api/client";
import { ErrorBox, Loading } from "../components/Loading";
import PlanCard from "../components/PlanCard";
import { dietService, planService } from "../services/dietService";

/**
 * GeneratePlanPage — the AI moment of the app.
 * Optional overrides (goal/diet/allergies) default from the saved profile.
 * Generating only PREVIEWS the plan; saving is an explicit action.
 */
export default function GeneratePlanPage() {
  const navigate = useNavigate();
  const [overrides, setOverrides] = useState({ goal: "", dietary_preference: "", allergies: "" });
  const [plan, setPlan] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const [savedMsg, setSavedMsg] = useState("");

  const set = (k) => (e) => setOverrides({ ...overrides, [k]: e.target.value });

  const generate = async (e) => {
    e.preventDefault();
    setError(""); setPlan(null); setSavedMsg(""); setLoading(true);
    try {
      const clean = Object.fromEntries(
        Object.entries(overrides).filter(([, v]) => v && v.trim() !== "")
      );
      setPlan(await dietService.generate(clean));
    } catch (err) {
      setError(apiError(err, "Plan generation failed — please try again"));
    } finally {
      setLoading(false);
    }
  };

  const save = async () => {
    try {
      await planService.save(plan);
      setSavedMsg("✅ Saved to your cloud dashboard!");
    } catch (err) {
      setError(apiError(err, "Could not save plan"));
    }
  };

  const download = () => {
    const text = [
      `AI DIET PLAN — ${plan.title}`,
      `(educational example — not medical advice)`,
      ``,
      `Breakfast: ${plan.breakfast}`,
      `Lunch:     ${plan.lunch}`,
      `Snack:     ${plan.snack}`,
      `Dinner:    ${plan.dinner}`,
      ``,
      `Nutrition (approx): ${plan.nutrition_summary.calories_kcal} kcal | ` +
        `protein ${plan.nutrition_summary.protein_g}g | carbs ${plan.nutrition_summary.carbs_g}g | ` +
        `fat ${plan.nutrition_summary.fat_g}g`,
      `Hydration: ${plan.nutrition_summary.hydration_reminder}`,
      ``,
      `Generated by: ${plan.engine_used} engine`,
    ].join("\n");
    const blob = new Blob([text], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "diet-plan.txt";
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="page">
      <h2>Generate your diet plan</h2>
      <ErrorBox message={error} />
      {savedMsg && <div className="success-box">{savedMsg}</div>}

      <form className="card form-card" onSubmit={generate}>
        <p className="form-note">Leave fields empty to use your saved profile defaults.</p>

        <label>Goal override</label>
        <select value={overrides.goal} onChange={set("goal")}>
          <option value="">— use my profile —</option>
          <option value="weight_loss">Weight-management</option>
          <option value="weight_gain">Weight-gain</option>
          <option value="maintenance">Maintenance</option>
          <option value="fitness">Fitness-oriented</option>
        </select>

        <label>Dietary preference override</label>
        <select value={overrides.dietary_preference} onChange={set("dietary_preference")}>
          <option value="">— use my profile —</option>
          <option value="vegetarian">Vegetarian</option>
          <option value="vegan">Vegan</option>
          <option value="eggetarian">Eggetarian</option>
          <option value="non_vegetarian">Non-vegetarian</option>
        </select>

        <label>Extra exclusions <small>(comma separated: nuts, dairy, gluten…)</small></label>
        <input value={overrides.allergies} onChange={set("allergies")} placeholder="e.g. soy" />

        <button className="btn btn-primary" disabled={loading}>
          {loading ? "Planning your day…" : "✨ Generate plan"}
        </button>
      </form>

      {loading && <Loading text="The recommendation engine is composing your meals…" />}

      {plan && (
        <PlanCard plan={plan}>
          <div className="plan-actions">
            <button className="btn btn-primary" onClick={save}>💾 Save to cloud</button>
            <button className="btn btn-outline" onClick={download}>⬇️ Export .txt</button>
            <button className="btn btn-outline" onClick={() => navigate("/plans")}>My saved plans</button>
          </div>
        </PlanCard>
      )}
    </div>
  );
}

"""
diet_engine.py — AI RECOMMENDATION ENGINE interface + factory + FALLBACK.

Two interchangeable engines behind one interface:

  RuleBasedEngine   deterministic rules over food_data.json (always available,
                    zero cost, offline)                     <- PRIMARY
  AIApiEngine       optional external AI API adapter        <- OPTIONAL
                    (env-configured key; ANY failure -> rule-based fallback)

The factory `get_diet_engine()` implements the fallback contract:

    IF AI API unavailable / slow / bad response
    THEN use the local rule-based engine
    AND record which engine actually produced the plan (`engine_used`)

This "graceful degradation" pattern is a headline cloud-resilience
demonstration: a failing third-party dependency never takes the
product down.
"""

import logging
from abc import ABC, abstractmethod

from backend.ai_engine.rule_based_engine import RuleBasedEngine, UserPreferences
from backend.config import settings

logger = logging.getLogger("diet.engine")


class DietEngineError(Exception):
    """Raised when plan generation fails in ALL engines."""


class DietPlanResult:
    """Uniform result shape returned by every engine."""

    __slots__ = (
        "title", "breakfast", "lunch", "snack", "dinner",
        "nutrition_summary", "engine_used", "goal", "dietary_preference",
    )

    def __init__(
        self,
        title: str,
        breakfast: str,
        lunch: str,
        snack: str,
        dinner: str,
        nutrition_summary: dict,
        engine_used: str,
        goal: str,
        dietary_preference: str,
    ) -> None:
        self.title = title
        self.breakfast = breakfast
        self.lunch = lunch
        self.snack = snack
        self.dinner = dinner
        self.nutrition_summary = nutrition_summary
        self.engine_used = engine_used
        self.goal = goal
        self.dietary_preference = dietary_preference

    def to_dict(self) -> dict:
        return {
            "title": self.title,
            "breakfast": self.breakfast,
            "lunch": self.lunch,
            "snack": self.snack,
            "dinner": self.dinner,
            "nutrition_summary": self.nutrition_summary,
            "engine_used": self.engine_used,
            "goal": self.goal,
            "dietary_preference": self.dietary_preference,
            "disclaimer": (
                "Educational/general wellness example — not medical or "
                "clinical nutrition advice."
            ),
        }


class DietEngine(ABC):
    """Interface both engines implement."""

    @abstractmethod
    def generate(self, prefs: UserPreferences) -> DietPlanResult:
        """Produce one day's plan for the given preferences."""


def get_diet_engine() -> DietEngine:
    """
    Factory + fallback orchestrator.

    AI_PROVIDER:
      rule_based -> always the local engine
      ai_api     -> try the AI API; fall back on ANY failure
      auto       -> AI API only if a key is configured; else rule-based
    """
    provider = settings.AI_PROVIDER.lower().strip()

    if provider in {"ai_api", "auto"}:
        if settings.AI_API_KEY and settings.AI_API_URL:
            from backend.ai_engine.ai_api_engine import AIApiEngine

            ai_engine = AIApiEngine()
            try:
                # Cheap probe: engine self-reports readiness (key present etc.)
                if ai_engine.is_ready():
                    return _FallbackEngine(ai_engine)
            except Exception as exc:  # noqa: BLE001 — never crash startup
                logger.warning("AI engine probe failed: %s", exc)
        logger.info("AI API not configured — using rule-based engine")

    return _FallbackEngine(RuleBasedEngine())


class _FallbackEngine(DietEngine):
    """
    Wrapper adding the resilience layer: tries the primary engine and
    falls back to the rule-based engine on any error, logging the
    degradation so the `engine_used` field tells the true story.
    """

    def __init__(self, primary: DietEngine, fallback: DietEngine | None = None) -> None:
        self._primary = primary
        self._fallback = fallback or RuleBasedEngine()

    def generate(self, prefs: UserPreferences) -> DietPlanResult:
        if isinstance(self._primary, RuleBasedEngine):
            return self._primary.generate(prefs)
        try:
            result = self._primary.generate(prefs)
            if not isinstance(result, DietPlanResult):
                # Defensive: a misbehaving adapter returned the wrong shape.
                raise TypeError("engine returned an invalid result type")
            logger.info("Plan generated by AI API engine")
            return result
        except Exception as exc:  # noqa: BLE001 — any failure triggers fallback
            logger.warning("AI API failed (%s) — falling back to rule-based engine", exc)
            return self._fallback.generate(prefs)
